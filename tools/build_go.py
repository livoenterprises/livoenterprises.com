#!/usr/bin/env python3
"""Regenerates go/**/index.html from go-keys.json. Run from the site folder: python3 tools/build_go.py
The key list is the one the app carries in LivoGoLinks.swift (keys are the guide's livo:// paths)."""
import json, os, html
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
rows = json.load(open(os.path.join(ROOT, "go-keys.json")))
tpl = open(os.path.join(ROOT, "tools", "page_template.html")).read()
nav = """      <a href="/products.html">Products</a>
      <a href="/about.html">About</a>
      <a href="/blog/">Notes</a>
      <a href="/support.html">Support</a>"""
out = ROOT
def page(key,title,where,guide,build):
    canon="https://livoenterprises.com/go/"+key
    body=('    <p>This link opens <strong>%s</strong> in Livo on your iPhone. If Livo is installed and you see this page instead, open Livo and go there by hand: %s</p>\n'
          '    <p>It needs Livo build <code>%s</code> or later (Settings, then Build, shows yours).</p>\n'
          '    <p><a href="/guide/%s.html">Read the guide page for this</a> &middot; <a href="/guide/">All of the Livo guide</a></p>\n'
          '    <p class="small">Livo links open a screen and never press anything for you. They carry no personal information and nothing about you is recorded.</p>')%(html.escape(title),html.escape(where),build,guide)
    h=tpl
    for a,b in {"{{source}}":"site/go-keys.json (tools/build_go.py)","{{title}}":html.escape(title),"{{description}}":html.escape("Opens "+title+" in Livo."),
        "{{canonical}}":canon,"{{nav}}":nav,"{{extra_top}}":'    <p class="small"><a href="/guide/">&larr; Livo guide</a></p>\n',"{{h1}}":html.escape(title),
        "{{updated}}":"","{{lede}}":'    <p class="lede">Open this link on your iPhone to go straight there.</p>\n',"{{wrap_class}}":"wrap","{{body}}":body}.items():
        h=h.replace(a,b)
    h=h.replace('GENERATED by tools/build_content.py from','GENERATED by tools/build_go.py from').replace(' Edit the .md file in content/, not this page.',' Edit go-keys.json, not this page.')
    return h.replace('<meta charset="utf-8">','<meta charset="utf-8">\n  <meta name="robots" content="noindex">',1)
for r in rows:
    d = os.path.join(out, "go", r["key"]); os.makedirs(d, exist_ok=True)
    open(os.path.join(d, "index.html"), "w").write(page(r["key"], r["title"], r["where"], r["guide"], r["build"]))
open(os.path.join(out, "go", "index.html"), "w").write(page("", "Livo links", "Open Livo, then the book icon (Organize).", "where-things-are", rows[0]["build"]).replace("This link opens <strong>Livo links</strong> in Livo on your iPhone.", "These links open screens in Livo on your iPhone."))
print("wrote", len(rows) + 1, "pages")
